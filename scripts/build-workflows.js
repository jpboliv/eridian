#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const { loadWorkflow } = require('./lib/workflows');

// Only invocation syntax and host metadata belong here. Behavioral policy lives
// in workflows/*.md and is embedded so installed skills are self-contained.
const WRAPPERS = [
  {
    file: 'commands/commit.md',
    workflow: 'commit',
    header:
      'description: Plain conventional commit from the staged diff\nallowed-tools: Bash(git:*)',
    invocation: 'Staged diff:\n\n!`git diff --cached --stat && git diff --cached`',
  },
  {
    file: 'commands/review.md',
    workflow: 'review',
    header:
      'description: One-line-per-finding Rocky review of the working diff (or a ref)\nargument-hint: "[base-ref or PR number]"\nallowed-tools: Bash(git:*), Bash(gh:*), Read, Grep, Glob',
    invocation:
      'Review target: `$ARGUMENTS` (if empty: `git diff HEAD`; if a ref: `git diff <ref>...HEAD`; if a PR number: `gh pr diff <number>`).',
  },
  {
    file: 'adapters/codex/skills/commit/SKILL.md',
    workflow: 'commit',
    header:
      'name: commit\ndescription: Preview and, only after confirmation, create a plain conventional commit from staged Codex workspace changes.',
    invocation: 'Read the staged workspace diff before drafting the message.',
  },
  {
    file: 'adapters/codex/skills/review/SKILL.md',
    workflow: 'review',
    header:
      'name: review\ndescription: Perform a read-only substantive review of the Codex workspace diff or a supplied revision.',
    invocation:
      'Review the working diff (`git diff HEAD`) unless the user supplies a revision or pull request.',
  },
];

function renderWorkflows() {
  return WRAPPERS.map(({ file, workflow, header, invocation }) => ({
    file,
    content: `---\n${header}\n---\n\n<!-- Generated by scripts/build-workflows.js from workflows/${workflow}.md. -->\n\n${invocation}\n\n${loadWorkflow(workflow)}\n`,
  }));
}

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.length && (args.length !== 1 || args[0] !== '--check')) {
    console.error('Usage: node scripts/build-workflows.js [--check]');
    process.exitCode = 1;
  } else {
    for (const { file, content } of renderWorkflows()) {
      const target = path.join(__dirname, '..', file);
      if (args[0] === '--check') {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
          console.error(`Stale workflow wrapper: ${file}. Run npm run build:workflows.`);
          process.exitCode = 1;
        }
      } else {
        fs.writeFileSync(target, content);
      }
    }
  }
}

module.exports = { renderWorkflows };
